CREATE TABLE document_chunk(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dev_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    source VARCHAR(20) NOT NULL,
    access_scope VARCHAR(20) NOT NULL,
    source_reference TEXT NOT NULL,
    embedding VECTOR(1024) NOT NULL,

    CONSTRAINT fk_document_chunk_dev FOREIGN KEY (dev_id) REFERENCES dev_profile(id) ON DELETE CASCADE,

    CONSTRAINT ck_document_chunk_source CHECK (source IN ('GITHUB', 'RESUME', 'PORTFOLIO')),

    CONSTRAINT ck_document_chunk_scope CHECK (access_scope IN ('PUBLIC', 'PRIVATE'))
);

CREATE INDEX idx_document_chunk_dev ON document_chunk(dev_id);

CREATE INDEX idx_document_chunk_dev_scope ON document_chunk(dev_id, access_scope);